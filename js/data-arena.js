/* ---------- 数独 4×4 生成器（袋鼠画图题） ----------
 * 模板盘 + 数字置换 + 行列组内交换，保证一定合法；挖空数按难度（6~10）。
 * 挖空后必须唯一解（判分严格比对 answer，多解会把孩子的合法填法误判成错）：
 * 不唯一就重新挖，反复不唯一则减少挖空数；Sudoku.countSolutions 由 ui-think.js 提供 */
function kangarooSudoku(blanks) {
  const base = [[1, 2, 3, 4], [3, 4, 1, 2], [2, 1, 4, 3], [4, 3, 2, 1]];
  /* 数字置换 */
  const perm = shuffle([1, 2, 3, 4]);
  let g = base.map(r => r.map(v => perm[v - 1]));
  /* 行交换（2×2 行组内交换保持合法）与列交换 */
  if (Math.random() < 0.5) { const t = g[0]; g[0] = g[1]; g[1] = t; }
  if (Math.random() < 0.5) { const t = g[2]; g[2] = g[3]; g[3] = t; }
  const swapCols = (a, b) => { for (let r = 0; r < 4; r++) { const t = g[r][a]; g[r][a] = g[r][b]; g[r][b] = t; } };
  if (Math.random() < 0.5) swapCols(0, 1);
  if (Math.random() < 0.5) swapCols(2, 3);
  /* 挖空：随机选位置清零（预填的用 0 表示空），挖完校验唯一解 */
  let want = blanks;
  for (let tries = 0; tries < 24; tries++) {
    const cells = shuffle([0, 1, 2, 3].flatMap(r => [0, 1, 2, 3].map(c => [r, c]))).slice(0, want);
    const puzzle = g.map(r => r.slice());
    cells.forEach(([r, c]) => { puzzle[r][c] = 0; });
    if (typeof Sudoku === 'undefined' || !Sudoku.countSolutions) return { puzzle, answer: g };
    /* countSolutions 依赖 Sudoku.n/boxR/boxC（玩过九宫局会被改掉），校验 4 宫盘前先锁定再还原 */
    const saved = { n: Sudoku.n, boxR: Sudoku.boxR, boxC: Sudoku.boxC };
    Sudoku.n = 4; Sudoku.boxR = 2; Sudoku.boxC = 2;
    const unique = Sudoku.countSolutions(puzzle.map(r => r.slice()), 2) === 1;
    Object.assign(Sudoku, saved);
    if (unique) return { puzzle, answer: g };
    if (tries % 6 === 5 && want > 4) want -= 2; /* 屡挖屡多解，就少挖两格降低难度 */
  }
  return { puzzle: g.map(r => r.slice()), answer: g }; /* 兜底：24 次都多解就给全盘（不会误判，等于送分题） */
}

